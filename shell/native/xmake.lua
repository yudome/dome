target("YudaeNative")
	add_rules("qt.qmlplugin")
	add_files("src/*.cpp", "generated/*.c")
	add_files("$(projectdir)/daemon/src/c/video.c", "$(projectdir)/daemon/src/c/settle.c")
	add_files("src/*.h")
	add_headerfiles("src/*.h")
	add_values("qt.qmlplugin.import_name", "Yudae.Native")
	add_values("qt.qmlplugin.majorversion", 1)
	add_values("qt.qmlplugin.minorversion", 0)
	add_values("qt.qmlplugin.qmldirfile", "qmldir")
	set_targetdir(path.join(os.projectdir(), "shell/native/qml"))
	add_includedirs("src", "generated", "$(projectdir)/daemon/src/c", "$(projectdir)/plugins/shadow/src")
	on_load(function (target)
		local private = os.dirs("/usr/include/qt6/QtGui/6.*")
		table.sort(private)
		assert(#private > 0, "Qt private headers missing under /usr/include/qt6/QtGui")
		target:add("includedirs", private[#private])
	end)
	add_includedirs("/usr/include/glib-2.0", "/usr/lib/glib-2.0/include", "/usr/include/gio-unix-2.0")
	add_links("gio-2.0", "gobject-2.0", "glib-2.0", "EGL", "GLESv2", "wayland-client", "avformat", "avcodec", "avutil", "swscale")
	add_cxflags("-fPIC")
	on_install(function (target)
		print(target:name() .. " runs from the repo")
	end)

target("yudae-pump")
