	set_basename("yudae-pump")
	add_includedirs("src", "/usr/include/qt6/QtGui")
	add_includedirs("/usr/include/glib-2.0", "/usr/lib/glib-2.0/include", "/usr/include/gio-unix-2.0")
	add_links("gio-2.0", "gobject-2.0", "glib-2.0", "Qt6Gui")
	set_targetdir(path.join(os.projectdir(), "daemon/zig-out/bin"))
	on_install(function (target)
		print(target:name() .. " runs from the repo")
	end)
